/**
 * Generates supabase/research-seed.sql from supabase/research-posts.seed.ts.
 *
 *   node supabase/generate-research-seed.ts
 *
 * The SQL upserts on slug, so running it again overwrites those posts (and
 * only those posts). Run it after schema.sql, in the Supabase SQL editor.
 */
import { writeFileSync } from "node:fs";
import { RESEARCH_POSTS, RESEARCH_SORT_START } from "./research-posts.seed.ts";

const text = (v: string | undefined | null) =>
  v == null ? "null" : `'${v.replace(/'/g, "''")}'`;
const json = (v: unknown) =>
  v == null ? "null" : `${text(JSON.stringify(v))}::jsonb`;
const num = (v: number | undefined | null) => (v == null ? "null" : String(v));

const columns = [
  "slug", "title", "subtitle", "excerpt", "category", "read_time",
  "published_at", "updated_at", "author", "hero_sketch", "keywords",
  "takeaways", "sections", "tags", "related_slugs", "cross_page_links",
  "faq", "featured", "popularity_score", "translations", "sort_order",
  "published",
];

const rows = RESEARCH_POSTS.map((p, i) =>
  [
    text(p.slug), text(p.title), text(p.subtitle), text(p.excerpt),
    text(p.category), num(p.readTime), text(p.publishedAt),
    text(p.updatedAt), json(p.author), text(p.heroSketch), json(p.keywords),
    json(p.takeaways), json(p.sections), json(p.tags), json(p.relatedSlugs),
    json(p.crossPageLinks), json(p.faq), String(!!p.featured),
    num(p.popularityScore), json(p.translations), String(RESEARCH_SORT_START + i), "true",
  ].join(",\n  ")
);

if (rows.length === 0) throw new Error("No research posts to write.");

const sql = `-- Generated by supabase/generate-research-seed.ts — ${RESEARCH_POSTS.length} research-desk posts.
-- Run after schema.sql in the Supabase SQL editor. Upserts on slug and touches
-- only these posts; the original posts (seed.sql) are not affected.

insert into public.blog_posts (
  ${columns.join(", ")}
) values
(
  ${rows.join("\n),\n(\n  ")}
)
on conflict (slug) do update set
  ${columns.filter((c) => c !== "slug").map((c) => `${c} = excluded.${c}`).join(",\n  ")};
`;

writeFileSync(new URL("./research-seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/research-seed.sql with ${RESEARCH_POSTS.length} posts.`);
